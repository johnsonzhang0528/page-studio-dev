import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createBillingDispatchOutbox } from '../lib/billing-dispatch-outbox.mjs';

const root=fs.mkdtempSync(path.join(os.tmpdir(),'billing-outbox-'));
const outbox=createBillingDispatchOutbox({root,clock:()=>1234});
const request='a'.repeat(64);
const result='b'.repeat(64);
const evidence='c'.repeat(64);
const input={invocation_id:'inv-1',idempotency_key:'idem-1',lease_id:'lease-1',request_sha256:request,parent_checkpoint:'checkpoint'};
const intent=outbox.createIntent(input);
assert.equal(intent.status,'INTENT_DURABLE');
assert.deepEqual(outbox.createIntent(input),intent);
assert.throws(()=>outbox.createIntent({...input,idempotency_key:'changed'}),error=>error.code==='BILLING_OUTBOX_CONFLICT');
const dispatch=outbox.authorizeDispatch('inv-1');
assert.equal(dispatch.fencing_generation,1);
assert.throws(()=>outbox.authorizeDispatch('inv-1'),error=>error.code==='BILLING_OUTBOX_DISPATCH_DENIED');
assert.throws(()=>outbox.markAccepted('inv-1',{dispatch_token:'wrong',fencing_generation:1,provider_request_id:'req-1'}),error=>error.code==='BILLING_OUTBOX_FENCE_REJECTED');
outbox.markAccepted('inv-1',{...dispatch,provider_request_id:'req-1'});
assert.equal(outbox.stageResult('inv-1',{...dispatch,provider_request_id:'req-1',result_sha256:result}).staged,true);
const secondInput={invocation_id:'inv-2',idempotency_key:'idem-2',lease_id:'lease-2',request_sha256:request,parent_checkpoint:'checkpoint'};
const second=outbox.createIntent(secondInput);
const old=outbox.authorizeDispatch(second.invocation_id);
outbox.markUnknown(second.invocation_id,{reason:'timeout'});
assert.throws(()=>outbox.authorizeDispatch(second.invocation_id),error=>error.code==='BILLING_OUTBOX_DISPATCH_DENIED');
const replacement=outbox.supersede(second.invocation_id,{reconciled_evidence_sha256:evidence});
assert.equal(replacement.fencing_generation,2);
const fresh=outbox.authorizeDispatch(second.invocation_id);
const late=outbox.stageResult(second.invocation_id,{...old,provider_request_id:'late-old',result_sha256:result});
assert.deepEqual(late,{staged:false,quarantined:true});
outbox.markAccepted(second.invocation_id,{...fresh,provider_request_id:'req-2'});
assert.equal(outbox.stageResult(second.invocation_id,{...fresh,provider_request_id:'req-2',result_sha256:result}).staged,true);
assert.equal(outbox.snapshot().quarantine.length,1);
fs.rmSync(root,{recursive:true,force:true});
console.log('BILLING_DISPATCH_OUTBOX_TESTS_OK');
